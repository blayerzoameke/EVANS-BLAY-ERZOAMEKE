type TranslationKey = keyof typeof translations['en'];

export function getTranslator(lang: Language): (key: TranslationKey, replacements?: { [key: string]: string | number }) => string {
  return (key: TranslationKey, replacements?: { [key: string]: string | number }): string => {
    const translationSet = translations[lang as keyof typeof translations] || translations.en;
    let text = translationSet[key] || translations.en[key] || key;

    if (replacements) {
        Object.keys(replacements).forEach(rKey => {
            const regex = new RegExp(`{${rKey}}`, 'g');
            text = text.replace(regex, String(replacements[rKey]));
        });
    }

    return text;
  };
}